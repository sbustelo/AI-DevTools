<?php
// PATH: ai0-0010/tools/patcher/patcher-view.php
declare(strict_types=1);

/**
 * @param array{parseErrors: array<int, string>, execResult: array<string, mixed>|null, flash: string|null, restoreUrl: string} $vm
 */
function patcher_render_view(array $vm): void
{
    $parseErrors = $vm['parseErrors'];
    $execResult = $vm['execResult'];
    $flash = $vm['flash'];
    $restoreUrl = htmlspecialchars($vm['restoreUrl'], ENT_QUOTES, 'UTF-8');
    ?>
    <?php if ($flash !== null): ?>
        <div class="j0ui-alert-inline j0ui-alert-success"><?= htmlspecialchars($flash, ENT_QUOTES, 'UTF-8') ?></div>
    <?php endif; ?>

    <?php if ($parseErrors !== []): ?>
        <div class="j0ui-alert-inline j0ui-alert-danger">
            <strong>Parse errors:</strong>
            <ul>
                <?php foreach ($parseErrors as $err): ?>
                    <li><?= htmlspecialchars($err, ENT_QUOTES, 'UTF-8') ?></li>
                <?php endforeach; ?>
            </ul>
        </div>
    <?php endif; ?>

    <?php if ($execResult !== null): ?>
        <section class="j0ui-card">
            <h2>Batch Result <code class="j0ui-mono"><?= htmlspecialchars($execResult['timestamp'], ENT_QUOTES, 'UTF-8') ?></code></h2>
            <?php if ($execResult['applied'] !== []): ?>
                <ul class="j0ui-mono">
                    <?php foreach ($execResult['applied'] as $item): ?>
                        <li><?= htmlspecialchars($item, ENT_QUOTES, 'UTF-8') ?></li>
                    <?php endforeach; ?>
                </ul>
            <?php endif; ?>

            <?php if (!empty($execResult['warnings'])): ?>
                <div class="j0ui-alert-inline j0ui-alert-warning">
                    <strong>Warnings (KaTeX / payload audit):</strong>
                    <ul class="j0ui-mono">
                        <?php foreach ($execResult['warnings'] as $warn): ?>
                            <li><?= htmlspecialchars($warn, ENT_QUOTES, 'UTF-8') ?></li>
                        <?php endforeach; ?>
                    </ul>
                </div>
            <?php endif; ?>

            <?php if ($execResult['errors'] !== []): ?>
                <div class="j0ui-alert-inline j0ui-alert-danger">
                    <strong>Failed operations (individually rolled back):</strong>
                    <?php
                    $reportLines = ["ERROR REPORT _ai0 (Batch {$execResult['timestamp']}):"];
                    foreach ($execResult['errors'] as $e) {
                        $reportLines[] = "- {$e['path']}: {$e['reason']}";
                    }
                    $reportLines[] = 'Regenerate only the failed blocks with exact START/END anchors.';
                    $reportText = implode("\n", $reportLines);
                    ?>
                    <textarea class="j0ui-textarea" rows="6" readonly data-j0-copy-source="patcher-err"><?= htmlspecialchars($reportText, ENT_QUOTES, 'UTF-8') ?></textarea>
                    <div class="j0ui-actions">
                        <button type="button" class="j0ui-btn" data-j0-action="copy-target" data-j0-target="patcher-err">Copy error report for AI</button>
                        <form method="post" class="j0ui-inline-form">
                            <input type="hidden" name="action" value="rollback_batch">
                            <input type="hidden" name="timestamp" value="<?= htmlspecialchars($execResult['timestamp'], ENT_QUOTES, 'UTF-8') ?>">
                            <button type="submit" class="j0ui-btn j0ui-btn--danger">Rollback entire batch</button>
                        </form>
                    </div>
                </div>
            <?php endif; ?>
        </section>
    <?php endif; ?>

    <section class="j0ui-card">
        <form method="post">
            <input type="hidden" name="action" value="apply">
            <h2>patcher — Apply AI Output</h2>
            <p class="j0ui-muted">Supports <code class="j0ui-mono">CREATE</code>, <code class="j0ui-mono">PATCH</code> (1-Line First), <code class="j0ui-mono">MOVE</code>, <code class="j0ui-mono">DISABLE</code> (<code class="j0ui-mono">_</code>), and <code class="j0ui-mono">DISCARD</code> (<code class="j0ui-mono">_🗑️</code>). Automatic <code class="j0ui-mono">_📦</code> backups on overwrite.</p>
            <textarea name="payload" class="j0ui-textarea" rows="16" placeholder="Paste the _ai0 block generated by the AI here..."></textarea>
            <div class="j0ui-actions">
                <button type="submit" class="j0ui-btn j0ui-btn--primary">Apply changes</button>
                <a class="j0ui-btn" href="<?= $restoreUrl ?>">Open restore</a>
            </div>
        </form>
    </section>
    <?php
}