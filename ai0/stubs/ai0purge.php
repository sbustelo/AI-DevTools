<?php
// PATH: ai0-0010/stubs/ai0purge.php
declare(strict_types=1);

if (!defined('J0_EXEC')) {
    define('J0_EXEC', true);
}

$stubConfig = [
    'repo_url'   => 'https://github.com/sbustelo/AI-DevTools',
    'on_missing' => 'strict',
    'cache_key'  => '__ai0_purge__',
    'targets'    => ['_ai0/tools/purge/index.php', 'ai0/tools/purge/index.php'],
];

(static function (string $startDir, array $cfg): void {
    $bs = chr(92);
    $origin = rtrim(str_replace($bs, '/', $startDir), '/');
    $routeFile = $origin . '/.j0route.php';
    $routes = [];

    if (@is_file($routeFile)) {
        $loaded = @include $routeFile;
        if (is_array($loaded)) {
            $routes = $loaded;
            $cached = $routes[$cfg['cache_key']] ?? '';
            if (is_string($cached) && $cached !== '' && @is_file($cached)) {
                $engineDir = rtrim(str_replace($bs, '/', dirname($cached, 3)), '/');
                $cachedRoot = dirname($engineDir);
                $baseDir = basename($engineDir);
                $sub = str_starts_with($origin . '/', $cachedRoot . '/') ? trim(substr($origin, strlen($cachedRoot)), '/') : '';
                $depth = $sub === '' ? 0 : count(explode('/', $sub));
                $GLOBALS['ai0_context'] = [
                    'root'       => $cachedRoot,
                    'match'      => $baseDir . '/tools/purge/index.php',
                    'base_dir'   => $baseDir,
                    'target_abs' => $cached,
                    'origin_abs' => $origin,
                    'up_rel'     => $depth === 0 ? '' : str_repeat('../', $depth),
                    'down_rel'   => $sub,
                ];
                require $cached;
                return;
            }
            unset($routes[$cfg['cache_key']]);
        }
    }

    $cursor = $origin;
    $down = [];

    for ($level = 0; $level <= 12; $level++) {
        foreach ($cfg['targets'] as $relTarget) {
            $candidate = $cursor . '/' . $relTarget;
            if (@is_file($candidate)) {
                if (is_writable($origin)) {
                    $routes[$cfg['cache_key']] = $candidate;
                    ksort($routes, SORT_NATURAL);
                    $payload = "<?php\n// Auto-generated by ai0purge stub. Safe to delete if ai0 moves.\nif (!defined('J0_EXEC')) {\n    exit;\n}\nreturn "
                        . var_export($routes, true)
                        . ";\n";
                    $tmp = $origin . '/.__j0route_' . uniqid('', true);
                    if (@file_put_contents($tmp, $payload) !== false && @rename($tmp, $routeFile)) {
                        if (function_exists('opcache_invalidate')) {
                            @opcache_invalidate($routeFile, true);
                        }
                    } else {
                        @unlink($tmp);
                    }
                }
                $GLOBALS['ai0_context'] = [
                    'root'       => $cursor,
                    'match'      => $relTarget,
                    'base_dir'   => explode('/', $relTarget)[0],
                    'target_abs' => $candidate,
                    'origin_abs' => $origin,
                    'up_rel'     => $level === 0 ? '' : str_repeat('../', $level),
                    'down_rel'   => $down === [] ? '' : implode('/', array_reverse($down)),
                ];
                require $candidate;
                return;
            }
        }
        $parent = dirname($cursor);
        if ($parent === $cursor) {
            break;
        }
        $down[] = basename($cursor);
        $cursor = $parent;
    }

    if ($cfg['on_missing'] === 'strict') {
        http_response_code(500);
        exit('This tool requires ai0 (' . $cfg['repo_url'] . '). Link ai0 as _ai0 in your project root.');
    }
})(__DIR__, $stubConfig);