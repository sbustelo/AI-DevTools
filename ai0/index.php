<?php
// PATH: ai0/index.php
declare(strict_types=1);

if (!defined('J0_EXEC')) {
    define('J0_EXEC', true);
}

$stubConfig = [
    'repo_url'   => 'https://github.com/sbustelo/AI-DevTools',
    'on_missing' => 'strict',
    'targets'    => ['_ai0/tools/index.php', 'ai0/tools/index.php'],
];

(static function (string $startDir, array $cfg): void {
    $bs = chr(92);
    $origin = rtrim(str_replace($bs, '/', $startDir), '/');
    $routeFile = $origin . '/.j0route.php';
    $routes = [];

    if (@is_file($routeFile)) {
        $loaded = @include $routeFile;
        if (is_array($loaded)) {
            $routes = $loaded;
            $cachedHub = $routes['__ai0_hub__'] ?? '';
            if (is_string($cachedHub) && $cachedHub !== '' && @is_file($cachedHub)) {
                $hubEngineDir = rtrim(str_replace($bs, '/', dirname($cachedHub, 2)), '/');
                $cachedRoot = dirname($hubEngineDir);
                $baseDir = basename($hubEngineDir);
                $isSelfEngine = ($origin === $hubEngineDir);

                if ($isSelfEngine) {
                    $upRel = '../';
                    $downRel = '';
                } elseif (str_starts_with($origin . '/', $cachedRoot . '/')) {
                    $sub = trim(substr($origin, strlen($cachedRoot)), '/');
                    $depth = $sub === '' ? 0 : count(explode('/', $sub));
                    $upRel = $depth === 0 ? '' : str_repeat('../', $depth);
                    $downRel = $sub;
                } else {
                    $upRel = '';
                    $downRel = '';
                }

                $GLOBALS['ai0_context'] = [
                    'root'       => $cachedRoot,
                    'match'      => $baseDir . '/tools/index.php',
                    'base_dir'   => $baseDir,
                    'target_abs' => $cachedHub,
                    'origin_abs' => $origin,
                    'up_rel'     => $upRel,
                    'down_rel'   => $downRel,
                ];
                require $cachedHub;
                return;
            }
            unset($routes['__ai0_hub__']);
        }
    }

    $cursor = $origin;
    $down = [];

    for ($level = 0; $level <= 12; $level++) {
        foreach ($cfg['targets'] as $relTarget) {
            $candidate = $cursor . '/' . $relTarget;
            if (@is_file($candidate)) {
                $hubEngineDir = rtrim(str_replace($bs, '/', dirname($candidate, 2)), '/');
                $isSelfEngine = ($origin === $hubEngineDir);

                if (!$isSelfEngine && is_writable($origin)) {
                    $routes['__ai0_hub__'] = $candidate;
                    ksort($routes, SORT_NATURAL);
                    $payload = "<?php\n// Auto-generated by ai0 stub. Safe to delete if ai0 moves.\nif (!defined('J0_EXEC')) {\n    exit;\n}\nreturn "
                        . var_export($routes, true)
                        . ";\n";
                    $tmp = $origin . '/.__j0route_' . uniqid('', true);
                    if (@file_put_contents($tmp, $payload) !== false && @rename($tmp, $routeFile)) {
                        if (function_exists('opcache_invalidate')) {
                            @opcache_invalidate($routeFile, true);
                        }
                    } else {
                        @unlink($tmp);
                    }
                }

                $GLOBALS['ai0_context'] = [
                    'root'       => $cursor,
                    'match'      => $relTarget,
                    'base_dir'   => explode('/', $relTarget)[0],
                    'target_abs' => $candidate,
                    'origin_abs' => $origin,
                    'up_rel'     => $level === 0 ? '' : str_repeat('../', $level),
                    'down_rel'   => $isSelfEngine ? '' : ($down === [] ? '' : implode('/', array_reverse($down))),
                ];
                require $candidate;
                return;
            }
        }
        $parent = dirname($cursor);
        if ($parent === $cursor) {
            break;
        }
        $down[] = basename($cursor);
        $cursor = $parent;
    }

    if ($cfg['on_missing'] === 'strict') {
        http_response_code(500);
        exit('This tool requires ai0 (' . $cfg['repo_url'] . '). Link ai0 as _ai0 in your project root.');
    }
})(__DIR__, $stubConfig);