/**
 * Resolves project root, active ai0 directory, 4-tier [_]ai0config domains, and _j0-temp vault.
 *
 * @return array{
 *   root: string,
 *   ai0_dir: string,
 *   domains: array<int, string>,
 *   temp_dir: string,
 *   match: string,
 *   base_dir: string,
 *   target_abs: string,
 *   origin_abs: string,
 *   up_rel: string,
 *   down_rel: string,
 *   via_stub: bool
 * }
 */
function ai0_resolve_context(string $fallbackDir): array
{
    ai0_guard_localhost();

    $bs = chr(92);
    $ai0Dir = str_replace($bs, '/', dirname(__DIR__));

    $docRoot = isset($_SERVER['DOCUMENT_ROOT']) ? rtrim(str_replace($bs, '/', (string) $_SERVER['DOCUMENT_ROOT']), '/') : '';
    $scriptName = isset($_SERVER['SCRIPT_NAME']) ? str_replace($bs, '/', (string) $_SERVER['SCRIPT_NAME']) : '';

    if (isset($GLOBALS['ai0_context']) && is_array($GLOBALS['ai0_context'])) {
        $ctx = $GLOBALS['ai0_context'];
        $ctx['via_stub'] = true;
        if ($docRoot !== '' && $scriptName !== '' && is_dir($docRoot)) {
            $ctxRoot = rtrim(str_replace($bs, '/', (string) ($ctx['root'] ?? '')), '/');
            if ($ctxRoot !== '' && $ctxRoot !== $docRoot && !str_starts_with($ctxRoot . '/', $docRoot . '/')) {
                $lexScriptDir = rtrim(dirname($docRoot . '/' . ltrim($scriptName, '/')), '/');
                $cursor = $lexScriptDir;
                for ($lvl = 0; $lvl <= 12; $lvl++) {
                    $bName = basename($cursor);
                    if (in_array($bName, ['ai0', '_ai0'], true) && is_file($cursor . '/core/ai0-context.php')) {
                        $ctx['base_dir'] = $bName;
                        $ctx['root'] = rtrim(dirname($cursor), '/') ?: '/';
                        break;
                    }
                    if ($cursor === $docRoot) {
                        break;
                    }
                    $parent = dirname($cursor);
                    if ($parent === $cursor) {
                        break;
                    }
                    $cursor = $parent;
                }
            }
        }
    } else {
        $ai0Clean = rtrim($ai0Dir, '/');
        $root = '';
        $baseDir = basename($ai0Clean);
        $scriptClean = '';

        if ($docRoot !== '' && $scriptName !== '' && is_dir($docRoot)) {
            $lexFile = $docRoot . '/' . ltrim($scriptName, '/');
            $scriptClean = rtrim(dirname($lexFile), '/');
            $cursor = $scriptClean;
            for ($lvl = 0; $lvl <= 12; $lvl++) {
                $baseName = basename($cursor);
                if (in_array($baseName, ['ai0', '_ai0'], true) && is_file($cursor . '/core/ai0-context.php')) {
                    $baseDir = $baseName;
                    $root = rtrim(dirname($cursor), '/') ?: '/';
                    break;
                }
                if ($cursor === $docRoot) {
                    break;
                }
                $parent = dirname($cursor);
                if ($parent === $cursor) {
                    break;
                }
                $cursor = $parent;
            }
        }

        if ($root === '') {
            $scriptFile = $_SERVER['SCRIPT_FILENAME'] ?? '';
            $scriptClean = $scriptFile !== ''
                ? rtrim(dirname(str_replace($bs, '/', $scriptFile)), '/')
                : rtrim(str_replace($bs, '/', $fallbackDir), '/');
            $root = rtrim(str_replace($bs, '/', dirname($ai0Clean)), '/') ?: '/';
        }

        if ($root !== '/' && str_starts_with($scriptClean . '/', $root . '/')) {
            $sub = trim(substr($scriptClean, strlen($root)), '/');
            $depth = $sub === '' ? 0 : count(explode('/', $sub));
            $upRel = $depth === 0 ? '' : str_repeat('../', $depth);
        } elseif ($root === '/' && $scriptClean !== '') {
            $sub = trim($scriptClean, '/');
            $depth = $sub === '' ? 0 : count(explode('/', $sub));
            $upRel = $depth === 0 ? '' : str_repeat('../', $depth);
        } else {
            $upRel = '';
        }

        $ctx = [
            'root'       => $root,
            'match'      => $baseDir,
            'base_dir'   => $baseDir,
            'target_abs' => $scriptClean,
            'origin_abs' => $root,
            'up_rel'     => $upRel,
            'down_rel'   => '',
            'via_stub'   => false,
        ];
    }

    $rootClean = rtrim($ctx['root'], '/');
    $mountPath = $rootClean . '/' . ($ctx['base_dir'] ?? basename($ai0Dir));
    $isContained = !is_link($mountPath)
        && !is_dir($rootClean . '/_ai0config')
        && !is_dir($rootClean . '/ai0config')
        && (is_dir($ai0Dir . '/_ai0config') || is_dir($ai0Dir . '/_j0-temp'));

    $ctx['ai0_dir'] = $ai0Dir;
    $ctx['domains'] = j0_config_domains($rootClean, $ai0Dir);
    $ctx['temp_dir'] = $isContained ? ($ai0Dir . '/_j0-temp') : ($rootClean . '/_j0-temp');
    $i18nCfg = j0_config_json('i18n', $ctx['domains']);
    $langs = (isset($i18nCfg['langs']) && is_array($i18nCfg['langs']) && $i18nCfg['langs'] !== [])
        ? $i18nCfg['langs']
        : ['en', 'es'];
    $ctx['langs'] = $langs;
    j0_i18n_config(['langs' => $langs]);

    $state = ai0_get_state($ctx);
    $savedProjRoot = rtrim(str_replace($bs, '/', (string) ($state['project_root'] ?? '')), '/');
    if (!empty($ctx['via_stub'])) {
        $projectRoot = $rootClean;
        if ($savedProjRoot !== $projectRoot) {
            $state['project_root'] = $projectRoot;
            ai0_save_state($ctx, $state);
        }
    } elseif ($savedProjRoot !== '' && !str_contains($savedProjRoot, '..') && is_dir($savedProjRoot)) {
        $projectRoot = $savedProjRoot;
    } else {
        $projectRoot = $rootClean;
    }
    $ctx['project_root'] = $projectRoot;

    j0_locate_init($rootClean !== '' ? $rootClean : $projectRoot);
    if (function_exists('j0_register_mount')) {
        if (is_dir($mountPath)) {
            j0_register_mount('ai0', $ai0Dir, $mountPath);
        }
        if (function_exists('j0_auto_bind_core_mounts')) {
            j0_auto_bind_core_mounts();
        }
    }
    $ai0Logical = is_dir($mountPath) ? $mountPath : $ai0Dir;
    $ctx['ai0_logical_dir'] = $ai0Logical;
    $mappedAi0Web = function_exists('j0_path_to_web_url') ? j0_path_to_web_url($ai0Logical) : null;
    $ctx['ai0_web_root'] = ($mappedAi0Web !== null && $mappedAi0Web !== '')
        ? (rtrim($mappedAi0Web, '/') . '/')
        : (($ctx['up_rel'] ?? '') . ($ctx['base_dir'] ?? 'ai0') . '/');

    return $ctx;
}

/**
 * @param array<string, mixed> $ctx
 * @return array<string, mixed>
 */
function ai0_get_state(array $ctx): array
{
    $stateFile = rtrim((string) $ctx['temp_dir'], '/') . '/ai0-state.json';
    $defaults = ['debug' => false];
    if (!is_file($stateFile)) {
        return $defaults;
    }
    $decoded = json_decode((string) file_get_contents($stateFile), true);
    if (!is_array($decoded)) {
        return $defaults;
    }
    return array_merge($defaults, $decoded);
}

/**
 * @param array<string, mixed> $ctx
 * @param array<string, mixed> $state
 */
function ai0_save_state(array $ctx, array $state): bool
{
    $tempDir = rtrim((string) $ctx['temp_dir'], '/');
    if (!is_dir($tempDir) && !mkdir($tempDir, 0775, true) && !is_dir($tempDir)) {
        return false;
    }
    $stateFile = $tempDir . '/ai0-state.json';
    $json = json_encode($state, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    return file_put_contents($stateFile, (string) $json) !== false;
}

/**
 * Updates and persists the active Project Root in <temp_dir>/ai0-state.json and declared roots registry.
 *
 * @param array<string, mixed> $ctx
 */
function ai0_set_project_root(array &$ctx, string $newRoot): bool
{
    $bs = chr(92);
    $clean = rtrim(str_replace($bs, '/', trim($newRoot)), '/');
    if ($clean === '') {
        $clean = '/';
    }
    if (str_contains($clean, '..') || !is_dir($clean)) {
        return false;
    }
    $state = ai0_get_state($ctx);
    $state['project_root'] = $clean;
    $ok = ai0_save_state($ctx, $state);
    if ($ok) {
        $ctx['project_root'] = $clean;
        ai0_write_root_marker($clean, ['is_project_root' => true], (string) ($ctx['temp_dir'] ?? ''));
    }
    return $ok;
}

/**
 * Creates a full project ZIP snapshot prefixed with _📦 (mechanical backup/archive).
 *
 * @return array{ok: bool, file: string, message: string}
 */
function ai0_create_zip_snapshot(string $projectRoot): array
{
    $rootClean = rtrim($projectRoot, '/');
    $projectName = basename($rootClean) ?: 'project';
    $stamp = date('Y m d Hi');
    $boxPrefix = "_\u{1F4E6}";
    $baseZip = "{$boxPrefix}{$projectName} {$stamp}.zip";
    $zipPath = $rootClean . '/' . $baseZip;

    $counter = 1;
    while (file_exists($zipPath)) {
        $baseZip = "{$boxPrefix}{$projectName} {$stamp} {$counter}.zip";
        $zipPath = $rootClean . '/' . $baseZip;
        $counter++;
    }

    $ignoreDirs = ['.git', 'node_modules', 'vendor'];

    if (class_exists('ZipArchive')) {
        $zip = new ZipArchive();
        if ($zip->open($zipPath, ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
            return ['ok' => false, 'file' => '', 'message' => 'Failed to initialize ZipArchive.'];
        }

        $iter = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($rootClean, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::LEAVES_ONLY
        );
        $baseLen = strlen($rootClean) + 1;

        /** @var SplFileInfo $file */
        foreach ($iter as $file) {
            if (!$file->isFile()) {
                continue;
            }
            $abs = $file->getPathname();
            $rel = substr($abs, $baseLen);
            $firstSeg = explode('/', $rel)[0];
            if (in_array($firstSeg, $ignoreDirs, true)) {
                continue;
            }
            $base = basename($rel);
            if (str_ends_with(strtolower($base), '.zip') && str_starts_with($base, $boxPrefix)) {
                continue;
            }
            $zip->addFile($abs, $rel);
        }
        $zip->close();
        return ['ok' => true, 'file' => $baseZip, 'message' => "Snapshot created: {$baseZip}"];
    }

    $cmd = 'cd ' . escapeshellarg($rootClean)
        . ' && /usr/bin/zip -rq ' . escapeshellarg($zipPath)
        . ' . -x ".git/*" "node_modules/*" "vendor/*" "_*.zip" 2>&1';
    $out = [];
    $code = 0;
    exec($cmd, $out, $code);
    if ($code !== 0) {
        return ['ok' => false, 'file' => '', 'message' => 'Failed to execute /usr/bin/zip: ' . implode(' ', $out)];
    }
    if (!is_file($zipPath)) {
        return ['ok' => false, 'file' => '', 'message' => 'ZIP snapshot file was not generated.'];
    }
    return ['ok' => true, 'file' => $baseZip, 'message' => "Snapshot created: {$baseZip}"];
}