<?php
// PATH: j0/quickstart/j0-bootstrap.php
declare(strict_types=1);

if (!function_exists('j0_boot')) {
    /**
     * Layer 0 Locator: locates and loads j0/api.php without hardcoded paths or Composer.
     *
     * Can be required as a file OR copy-pasted directly into any PHP script.
     * Traverses upward lexically from the caller directory (preserving symlinks)
     * and caches '__j0_api__' in a sibling .j0route.php associative map for O(1) boots.
     *
     * @param string $originDir Starting directory (defaults to caller file's directory)
     * @param array<string, mixed> $options Optional overrides: targets, cache_route, max_levels, on_missing, repo_url
     */
    function j0_boot(string $originDir = '', array $options = []): bool
    {
        if (!defined('J0_EXEC')) {
            define('J0_EXEC', true);
        }

        if (function_exists('j0_api')) {
            return true;
        }

        $cfg = array_merge([
            'repo_url'    => 'https://j0.bustelo.com.ar/',
            'on_missing'  => 'strict', // 'strict' = HTTP 500 + exit | 'silent' = return false
            'cache_route' => true,     // Persists '__j0_api__' inside .j0route.php
            'max_levels'  => 12,
            'targets'     => [
                '_j0/api.php',
                'j0/api.php',
                'vendors/j0/api.php',
                'vendor/j0/api.php',
                '_ai0/j0/api.php',
                'ai0/j0/api.php',
            ],
        ], $options);

        $bs = chr(92);
        if ($originDir === '') {
            $trace = debug_backtrace(DEBUG_BACKTRACE_IGNORE_ARGS, 1);
            $callerFile = $trace[0]['file'] ?? __FILE__;
            $originDir = dirname($callerFile);
        }

        $origin = rtrim(str_replace($bs, '/', $originDir), '/');
        $routeFile = $origin . '/.j0route.php';
        $legacyRoute = $origin . '/_j0route.php';
        $routes = [];

        if (!empty($cfg['cache_route'])) {
            if (@is_file($routeFile)) {
                $loaded = @include $routeFile;
                if (is_array($loaded)) {
                    $cachedOrigin = $loaded['__j0_origin__'] ?? '';
                    if (is_string($cachedOrigin) && $cachedOrigin === $origin) {
                        $routes = $loaded;
                        $cachedApi = $routes['__j0_api__'] ?? '';
                        if (is_string($cachedApi) && $cachedApi !== '' && @is_file($cachedApi)) {
                            require_once $cachedApi;
                            return true;
                        }
                        unset($routes['__j0_api__']);
                    }
                }
            } elseif (@is_file($legacyRoute)) {
                $legacyApi = @include $legacyRoute;
                @unlink($legacyRoute);
                if (is_string($legacyApi) && $legacyApi !== '' && @is_file($legacyApi)) {
                    $routes['__j0_api__'] = $legacyApi;
                    if (is_writable($origin)) {
                        $payload = "<?php\n// Auto-generated by j0_boot(). Safe to delete if files move.\nif (!defined('J0_EXEC')) {\n    exit;\n}\nreturn "
                            . var_export($routes, true)
                            . ";\n";
                        $tmp = $origin . '/.__j0route_' . uniqid('', true);
                        if (@file_put_contents($tmp, $payload) !== false && @rename($tmp, $routeFile)) {
                            if (function_exists('opcache_invalidate')) {
                                @opcache_invalidate($routeFile, true);
                            }
                        } else {
                            @unlink($tmp);
                        }
                    }
                    require_once $legacyApi;
                    return true;
                }
            }
        }

        $cursor = $origin;
        $maxLevels = (int) ($cfg['max_levels'] ?? 12);

        for ($level = 0; $level <= $maxLevels; $level++) {
            foreach ($cfg['targets'] as $relTarget) {
                $cleanTarget = ltrim(str_replace($bs, '/', (string) $relTarget), '/');
                $candidate = $cursor . '/' . $cleanTarget;
                if (@is_file($candidate)) {
                    if (!empty($cfg['cache_route']) && is_writable($origin)) {
                        $routes['__j0_origin__'] = $origin;
                        $routes['__j0_api__'] = $candidate;
                        ksort($routes, SORT_NATURAL);
                        $payload = "<?php\n// Auto-generated by j0_boot(). Safe to delete if files move.\nif (!defined('J0_EXEC')) {\n    exit;\n}\nreturn "
                            . var_export($routes, true)
                            . ";\n";
                        $tmp = $origin . '/.__j0route_' . uniqid('', true);
                        if (@file_put_contents($tmp, $payload) !== false && @rename($tmp, $routeFile)) {
                            if (function_exists('opcache_invalidate')) {
                                @opcache_invalidate($routeFile, true);
                            }
                        } else {
                            @unlink($tmp);
                        }
                    }
                    require_once $candidate;
                    return true;
                }
            }

            $parent = dirname($cursor);
            if ($parent === $cursor) {
                break;
            }
            $cursor = $parent;
        }

        if (($cfg['on_missing'] ?? 'strict') === 'strict') {
            http_response_code(500);
            exit('This application requires j0 (' . $cfg['repo_url'] . '). Link or place j0 in your project root.');
        }

        return false;
    }
}